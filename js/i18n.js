  function detect() {
    try {
      var saved = root.localStorage && root.localStorage.getItem('sg-lang');
      if (saved && STRINGS[saved]) return saved;
    } catch (e) { /* storage blocked: ignore */ }
    var nav = (root.navigator && root.navigator.language) || 'es';
    return nav.toLowerCase().indexOf('es') === 0 ? 'es' : 'en';
  }

  function setLang(lang) {
    if (!STRINGS[lang]) return;
    current = lang;
    try { root.localStorage && root.localStorage.setItem('sg-lang', lang); } catch (e) { /* ignore */ }
  }

  /** Translate a key, replacing {placeholders} with params. */
  function t(key, params) {
    var s = (STRINGS[current] && STRINGS[current][key]);
    if (s === undefined) s = STRINGS.es[key];
    if (s === undefined) s = key;
    if (params) Object.keys(params).forEach(function (k) { s = s.split('{' + k + '}').join(String(params[k])); });
    return s;
  }

